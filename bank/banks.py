def find_bank_by_iban(iban: str):
    if not iban:
        return None
    clean = "".join(iban.split()).upper()
    if clean.startswith("TR") and len(clean) >= 9:
        code_5 = clean[4:9]
        # Compare 5-digit code or stripped leading zero
        code_4 = code_5[1:] if code_5.startswith("0") else code_5
        for b in TURKISH_BANKS:
            if b["iban_code"] == code_5 or b["code"] == code_4 or b["code"] == code_5:
                return b
    return None

def find_bank_by_code(code: str):
    if not code:
        return None
    c = str(code).strip()
    for b in TURKISH_BANKS:
        if b["code"] == c or b["iban_code"] == c or b["code"] == c.zfill(4):
            return b
    return None

def find_bank_by_name(name: str):
    if not name:
        return None
    n = name.strip().lower()
    for b in TURKISH_BANKS:
        if (n in b["official_name"].lower() or 
            b["official_name"].lower() in n or 
            n in b["short_name"].lower() or 
            b["short_name"].lower() in n):
            return b
    return None
